#!/usr/bin/env python3
"""build-quote-fonts.py [NOTO_DIR] [NOTO_CJK_DIR]: tiny fonts for the living-room quotes.

A TV browser often has no fonts for Arabic, Chinese, Amharic or Tamil and would draw empty
boxes. This reads assets/ui/quotes.js, takes exactly the characters the quotes use in each
script and cuts the matching Noto font (SIL Open Font License) down to those glyphs as WOFF2,
then writes assets/ui/quote-fonts.css with one @font-face per piece. Run it again after
changing the quotes. Needs fontTools and brotli (pip install fonttools brotli).
"""
import json
import pathlib
import re
import sys

from fontTools import subset
from fontTools.ttLib import TTCollection, TTFont

ROOT = pathlib.Path(__file__).resolve().parents[1]
UI = ROOT / 'assets' / 'ui'
NOTO = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/noto')
CJK = pathlib.Path(sys.argv[2] if len(sys.argv) > 2 else '/usr/share/fonts/noto-cjk')

# script fonts (family "SBC World", chosen per character by unicode-range)
SCRIPTS = [
    ('base', 'NotoSans-Regular.ttf'), ('arab', 'NotoSansArabic-Regular.ttf'),
    ('hebr', 'NotoSansHebrew-Regular.ttf'), ('deva', 'NotoSansDevanagari-Regular.ttf'),
    ('beng', 'NotoSansBengali-Regular.ttf'), ('taml', 'NotoSansTamil-Regular.ttf'),
    ('thai', 'NotoSansThai-Regular.ttf'), ('ethi', 'NotoSansEthiopic-Regular.ttf'),
]
# Han characters look different per language, so each CJK language gets its own family
CJK_FACES = {'ja': ('jp', 'Noto Sans CJK JP'), 'ko': ('kr', 'Noto Sans CJK KR'),
             'zh-Hans': ('sc', 'Noto Sans CJK SC'), 'zh-Hant': ('tc', 'Noto Sans CJK TC')}

text = (UI / 'quotes.js').read_text(encoding='utf-8')
items = re.findall(r"\{o: '((?:[^'\\]|\\.)*)', l: '([^']+)'", text)
items = [(o.encode().decode('unicode_escape').encode('latin-1').decode('utf-8') if '\\' in o else o, l) for o, l in items]

css = ['/* generated by tools/build-quote-fonts.py: Noto glyph subsets (SIL OFL 1.1) */']
cjk_chars: dict[str, set[str]] = {}
other_chars: set[str] = set()
for original, lang in items:
    if lang in CJK_FACES:
        cjk_chars.setdefault(lang, set()).update(original)
    else:
        other_chars.update(original)

def save(font, chars, name):
    opts = subset.Options(); opts.flavor = 'woff2'; opts.layout_features = ['*']; opts.name_IDs = ['*']
    sub = subset.Subsetter(options=opts)
    sub.populate(text=''.join(sorted(chars)))
    sub.subset(font)
    path = UI / f'qf-{name}.woff2'
    font.flavor = 'woff2'
    font.save(path)
    return path

def ranges(codepoints):
    cps = sorted(codepoints); out = []; start = prev = None
    for cp in cps:
        if start is None: start = prev = cp
        elif cp == prev + 1: prev = cp
        else: out.append((start, prev)); start = prev = cp
    if start is not None: out.append((start, prev))
    return ', '.join(f'U+{a:X}' if a == b else f'U+{a:X}-{b:X}' for a, b in out)

for name, file in SCRIPTS:
    font = TTFont(NOTO / file)
    cmap = font.getBestCmap()
    covered = {c for c in other_chars if ord(c) in cmap and (name != 'base' or ord(c) < 0x590 or 0x1E00 <= ord(c) <= 0x1FFF or 0x2000 <= ord(c) <= 0x206F)}
    if name != 'base':
        covered = {c for c in covered if ord(c) > 0x7F}  # the base font carries Latin
    if not covered:
        continue
    path = save(font, covered, name)
    css.append(f"@font-face {{ font-family: 'SBC World'; src: url('/assets/ui/{path.name}') format('woff2'); "
               f"unicode-range: {ranges(ord(c) for c in covered)}; font-display: swap; }}")
    print(f'{path.name}: {len(covered)} glyphs, {path.stat().st_size} bytes')

collection = TTCollection(CJK / 'NotoSansCJK-Regular.ttc')
for lang, chars in sorted(cjk_chars.items()):
    short, family = CJK_FACES[lang]
    face = next(f for f in collection.fonts if f['name'].getDebugName(1) == family)
    path = save(face, chars, f'cjk-{short}')
    css.append(f"@font-face {{ font-family: 'SBC CJK {short.upper()}'; src: url('/assets/ui/{path.name}') format('woff2'); font-display: swap; }}")
    css.append(f".lr-orig:lang({lang}) {{ font-family: 'SBC CJK {short.upper()}', 'SBC World', sans-serif; }}")
    print(f'{path.name}: {len(chars)} glyphs, {path.stat().st_size} bytes')

(UI / 'quote-fonts.css').write_text('\n'.join(css) + '\n', encoding='utf-8')
print(f'quote-fonts.css: {len(css) - 1} rules')
